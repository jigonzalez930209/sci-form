#!/usr/bin/env python3
"""Generate the MMFF94 OOP, stretch-bend, PBCI and bond-charge tables.

The main generator (``gen_mmff94_params.py``) emits the bond/angle/torsion/vdW
tables.  This companion emits the tables needed by the full MMFF94 energy:
``defaultMMFFOop`` / ``defaultMMFFsOop``, ``defaultMMFFStbn``,
``defaultMMFFDfsb``, ``defaultMMFFPBCI`` and ``defaultMMFFChg`` from the
vendored RDKit ``Params.cpp`` (BSD-3-Clause; parameter data © Merck and Co.,
Inc., 1994-1996).

Usage:
    python scripts/validation/gen_mmff94_extra_params.py
"""

from __future__ import annotations

import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
SRC = ROOT / "scripts" / "validation" / "upstream" / "mmff94" / "Params.cpp"
OUT = ROOT / "src" / "forcefield" / "mmff94_extra_params.rs"


def extract(src: str, name: str) -> str:
    m = re.search(
        r"const\s+std::string\s+"
        + re.escape(name)
        + r'\s*=\s*((?:"(?:[^"\\]|\\.)*"\s*)+);',
        src,
        re.S,
    )
    if not m:
        raise KeyError(name)
    return (
        "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1)))
        .replace("\\t", "\t")
        .replace("\\n", "\n")
    )


def rows(blob: str) -> list[list[str]]:
    out = []
    for line in blob.splitlines():
        if not line or line[0] == "*":
            continue
        fields = [f.strip() for f in line.split("\t")]
        if fields and fields[0]:
            out.append(fields)
    return out


def oop_rows(blob: str) -> list[tuple[int, int, int, int, float]]:
    out = []
    for r in rows(blob):
        if len(r) >= 5 and r[0].isdigit() and r[1].isdigit():
            i, j, k, l = int(r[0]), int(r[1]), int(r[2]), int(r[3])
            # RDKit sorts the three substituents by equivalence level before
            # the lookup; the published table is not always stored that way.
            i, k, l = sorted((i, k, l))
            out.append((i, j, k, l, float(r[4])))
    return sorted(set(out))


def stbn_rows(blob: str) -> list[tuple[int, int, int, int, float, float]]:
    out = []
    for r in rows(blob):
        if len(r) >= 6 and all(x.isdigit() for x in r[:4]):
            t, i, j, k = int(r[0]), int(r[1]), int(r[2]), int(r[3])
            a, b = float(r[4]), float(r[5])
            # Canonical storage keeps i <= k; swapping the wings swaps the two
            # force constants.
            if i > k:
                i, k, a, b = k, i, b, a
            out.append((t, i, j, k, a, b))
    return sorted(set(out))


def dfsb_rows(blob: str) -> list[tuple[int, int, int, float, float]]:
    out = []
    for r in rows(blob):
        if len(r) >= 5 and all(x.isdigit() for x in r[:3]):
            i, j, k = int(r[0]), int(r[1]), int(r[2])
            a, b = float(r[3]), float(r[4])
            if i > k:
                i, k, a, b = k, i, b, a
            out.append((i, j, k, a, b))
    return sorted(set(out))


def pbci_rows(blob: str) -> list[tuple[int, float, float]]:
    out = []
    for r in rows(blob):
        # first column is a version marker (always 0); the type is second
        if len(r) >= 4 and r[1].isdigit():
            out.append((int(r[1]), float(r[2]), float(r[3])))
    return sorted(set(out))


def chg_rows(blob: str) -> list[tuple[int, int, int, float]]:
    out = []
    for r in rows(blob):
        if len(r) >= 4 and all(x.isdigit() for x in r[:3]):
            out.append((int(r[0]), int(r[1]), int(r[2]), float(r[3])))
    return sorted(set(out))


def emit_oop(name: str, table: list[tuple[int, int, int, int, float]]) -> list[str]:
    out = [
        f"/// Out-of-plane parameters for `{name}`.",
        "///",
        "/// Central atom `j_type`; the three substituents are stored canonically",
        "/// sorted by equivalence level, matching RDKit's lookup.",
        "#[rustfmt::skip]",
        f"pub static {name.upper()}: &[Mmff94OopParam] = &[",
    ]
    out += [
        f"    Mmff94OopParam {{ i_type: {i}, j_type: {j}, k_type: {k}, l_type: {l}, koop: {v:.6} }},"
        for i, j, k, l, v in table
    ]
    out += ["];", ""]
    return out


def main() -> None:
    src = SRC.read_text()
    sha = hashlib.sha256(src.encode()).hexdigest()

    oop = oop_rows(extract(src, "defaultMMFFOop"))
    oop_s = oop_rows(extract(src, "defaultMMFFsOop"))
    stbn = stbn_rows(extract(src, "defaultMMFFStbn"))
    dfsb = dfsb_rows(extract(src, "defaultMMFFDfsb"))
    pbci = pbci_rows(extract(src, "defaultMMFFPBCI"))
    chg = chg_rows(extract(src, "defaultMMFFChg"))

    out = [
        "//! Extra MMFF94 tables for the full energy (OOP, stretch-bend, charges).",
        "//!",
        "//! Generated by `scripts/validation/gen_mmff94_extra_params.py` from the",
        "//! vendored RDKit `Params.cpp`; do not edit by hand.",
        f"//! Upstream SHA-256: `{sha}`",
        "//!",
        "//! Parameter data © Merck and Co., Inc., 1994-1996; RDKit is BSD-3-Clause.",
        "#![allow(clippy::approx_constant)]",
        "",
        "/// Out-of-plane parameter: central atom `j` with substituents `i, k, l`.",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct Mmff94OopParam {",
        "    /// First substituent type.",
        "    pub i_type: u8,",
        "    /// Central atom type.",
        "    pub j_type: u8,",
        "    /// Second substituent type.",
        "    pub k_type: u8,",
        "    /// Third substituent type.",
        "    pub l_type: u8,",
        "    /// Force constant in md·Å/rad².",
        "    pub koop: f64,",
        "}",
        "",
    ]
    out += emit_oop("mmff94_oop_params", oop)
    out += emit_oop("mmff94s_oop_params", oop_s)
    out += [
        "/// Stretch-bend parameter for an angle `i-j-k`.",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct Mmff94StbnParam {",
        "    /// Stretch-bend type.",
        "    pub st_type: u8,",
        "    /// First wing atom type.",
        "    pub i_type: u8,",
        "    /// Central atom type.",
        "    pub j_type: u8,",
        "    /// Second wing atom type.",
        "    pub k_type: u8,",
        "    /// Force constant for the `i-j` bond.",
        "    pub kba_ijk: f64,",
        "    /// Force constant for the `k-j` bond.",
        "    pub kba_kji: f64,",
        "}",
        "",
        "#[rustfmt::skip]",
        "pub static MMFF94_STBN_PARAMS: &[Mmff94StbnParam] = &[",
    ]
    out += [
        f"    Mmff94StbnParam {{ st_type: {t}, i_type: {i}, j_type: {j}, k_type: {k}, kba_ijk: {a:.6}, kba_kji: {b:.6} }},"
        for t, i, j, k, a, b in stbn
    ]
    out += [
        "];",
        "",
        "/// Default stretch-bend parameter keyed by periodic-table rows.",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct Mmff94DfsbParam {",
        "    /// Periodic-table row of the first atom.",
        "    pub row_i: u8,",
        "    /// Periodic-table row of the central atom.",
        "    pub row_j: u8,",
        "    /// Periodic-table row of the third atom.",
        "    pub row_k: u8,",
        "    /// Force constant for the first bond.",
        "    pub kba_ijk: f64,",
        "    /// Force constant for the second bond.",
        "    pub kba_kji: f64,",
        "}",
        "",
        "#[rustfmt::skip]",
        "pub static MMFF94_DFSB_PARAMS: &[Mmff94DfsbParam] = &[",
    ]
    out += [
        f"    Mmff94DfsbParam {{ row_i: {i}, row_j: {j}, row_k: {k}, kba_ijk: {a:.6}, kba_kji: {b:.6} }},"
        for i, j, k, a, b in dfsb
    ]
    out += [
        "];",
        "",
        "/// Partial bond-charge increment and formal-charge adjustment per type.",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct Mmff94PbciParam {",
        "    /// MMFF94 atom type.",
        "    pub atom_type: u8,",
        "    /// Partial bond-charge increment.",
        "    pub pbci: f64,",
        "    /// Formal-charge adjustment factor.",
        "    pub fcadj: f64,",
        "}",
        "",
        "#[rustfmt::skip]",
        "pub static MMFF94_PBCI_PARAMS: &[Mmff94PbciParam] = &[",
    ]
    out += [
        f"    Mmff94PbciParam {{ atom_type: {t}, pbci: {p:.6}, fcadj: {f:.6} }},"
        for t, p, f in pbci
    ]
    out += [
        "];",
        "",
        "/// Bond-charge increment for a bond type and ordered atom types.",
        "#[derive(Debug, Clone, Copy)]",
        "pub struct Mmff94ChgParam {",
        "    /// MMFF94 bond type.",
        "    pub bond_type: u8,",
        "    /// First atom type (canonically the smaller one).",
        "    pub i_type: u8,",
        "    /// Second atom type.",
        "    pub j_type: u8,",
        "    /// Bond-charge increment.",
        "    pub bci: f64,",
        "}",
        "",
        "#[rustfmt::skip]",
        "pub static MMFF94_CHG_PARAMS: &[Mmff94ChgParam] = &[",
    ]
    out += [
        f"    Mmff94ChgParam {{ bond_type: {t}, i_type: {i}, j_type: {j}, bci: {b:.6} }},"
        for t, i, j, b in chg
    ]
    out += ["];", ""]

    OUT.write_text("\n".join(out))
    print(
        f"wrote {OUT.relative_to(ROOT)}: oop={len(oop)} oop_s={len(oop_s)} "
        f"stbn={len(stbn)} dfsb={len(dfsb)} pbci={len(pbci)} chg={len(chg)}"
    )


if __name__ == "__main__":
    main()
