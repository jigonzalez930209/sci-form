from refdata import ref_data_dir, skip

ROOT = Path(__file__).resolve().parent.parent.parent
FIX = ROOT / "tests" / "fixtures" / "validation" / "gfn0_params.json"
OUT = ROOT / "src" / "xtb" / "gfn0_params.rs"

L_OF = {"s": 0, "p": 1, "d": 2, "f": 3}

# xtb paulingEN default (src/param/paulingen.f90); used when the GFN0 file
