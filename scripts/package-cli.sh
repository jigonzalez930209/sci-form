#!/usr/bin/env bash
# Package the sci-form CLI for one target.
#
#   scripts/package-cli.sh <target-triple> [out-dir]
#
# Expects `cargo build --release -p sci-form-cli --target <triple>` to have run.
# Produces, in <out-dir> (default: dist/):
#   sci-form-<version>-<triple>.tar.gz   (Linux, macOS)  or  .zip (Windows)
#   sci-form_<version>_<arch>.deb  and  sci-form-<version>.<arch>.rpm   (Linux)
# plus a SHA256SUMS line for each file in <out-dir>/SHA256SUMS.
set -euo pipefail

TARGET="${1:?usage: package-cli.sh <target-triple> [out-dir]}"
OUT="${2:-dist}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

VERSION="$(sed -n 's/^version = "\(.*\)"$/\1/p' crates/cli/Cargo.toml | head -1)"
EXE="sci-form"
case "$TARGET" in *windows*) EXE="sci-form.exe" ;; esac
BIN="target/$TARGET/release/$EXE"
[ -f "$BIN" ] || BIN="target/release/$EXE"
[ -f "$BIN" ] || { echo "binary not found for $TARGET (build it first)"; exit 1; }

mkdir -p "$OUT" target/completions
# Completions are generated by the binary itself, so they list the real commands.
if [ "${TARGET#*windows}" = "$TARGET" ] && "$BIN" --version >/dev/null 2>&1; then
  "$BIN" completions bash > target/completions/sci-form.bash
  "$BIN" completions zsh  > target/completions/_sci-form
  "$BIN" completions fish > target/completions/sci-form.fish
else
  # Cross-compiled binary that cannot run here: reuse the host's completions
  # (the command set is identical across targets).
  HOSTBIN="target/release/$EXE"
  if [ -x "$HOSTBIN" ]; then
    "$HOSTBIN" completions bash > target/completions/sci-form.bash
    "$HOSTBIN" completions zsh  > target/completions/_sci-form
    "$HOSTBIN" completions fish > target/completions/sci-form.fish
  fi
fi

NAME="sci-form-$VERSION-$TARGET"
STAGE="$(mktemp -d)/$NAME"
mkdir -p "$STAGE/completions"
cp "$BIN" "$STAGE/"
cp README.md LICENSE "$STAGE/"
cp target/completions/* "$STAGE/completions/" 2>/dev/null || true
cat > "$STAGE/INSTALL.txt" <<EOT
sci-form $VERSION

Linux / macOS:  copy 'sci-form' to a folder on your PATH, e.g.
                  sudo install -m 755 sci-form /usr/local/bin/
Windows:        copy 'sci-form.exe' to a folder on your PATH.

Then run:       sci-form            (a short guide)
                sci-form commands   (every command, by topic)
                sci-form examples pm3 --run
Completions:    completions/ (bash, zsh, fish)
Documentation:  https://sci-form.dev
EOT

case "$TARGET" in
  *windows*)
    if command -v zip >/dev/null 2>&1; then
      (cd "$(dirname "$STAGE")" && zip -qr "$ROOT/$OUT/$NAME.zip" "$NAME")
    else
      # Windows runners: 7-Zip is installed, zip(1) may not be.
      (cd "$(dirname "$STAGE")" && 7z a -tzip -bso0 "$(cygpath -w "$ROOT/$OUT/$NAME.zip" 2>/dev/null || echo "$ROOT/$OUT/$NAME.zip")" "$NAME")
    fi ;;
  *)         tar -C "$(dirname "$STAGE")" -czf "$OUT/$NAME.tar.gz" "$NAME" ;;
esac

# .deb / .rpm for Linux targets (tools are optional locally, required in CI).
case "$TARGET" in
  *linux*)
    # Use --target only when the binary was built for it (CI); a host build
    # lives in target/release.
    TFLAG=(); [ -f "target/$TARGET/release/$EXE" ] && TFLAG=(--target "$TARGET")
    if command -v cargo-deb >/dev/null 2>&1; then
      cargo deb -p sci-form-cli --no-build --no-strip "${TFLAG[@]}" --output "$OUT/"
    else echo "cargo-deb not installed: skipping .deb"; fi
    if command -v cargo-generate-rpm >/dev/null 2>&1; then
      cargo generate-rpm -p crates/cli "${TFLAG[@]}" -o "$OUT/"
    else echo "cargo-generate-rpm not installed: skipping .rpm"; fi
    ;;
esac

(cd "$OUT" && rm -f SHA256SUMS && { sha256sum * 2>/dev/null || shasum -a 256 *; } > SHA256SUMS)
ls -l "$OUT"
